export function getAllBlogPosts(): BlogPost[] {
  return BLOG_POSTS.sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime());
}

export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  return BLOG_POSTS.find((post) => post.slug === slug);
}

export function getFeaturedBlogPost(): BlogPost {
  return BLOG_POSTS.find((post) => post.featured) || BLOG_POSTS[0];
}

export function getRelatedBlogPosts(currentSlug: string, category?: string, limit: number = 3): BlogPost[] {
  return BLOG_POSTS
    .filter((post) => post.slug !== currentSlug)
    .filter((post) => (category ? post.category === category : true))
    .slice(0, limit);
}

export function searchBlogPosts(query: string, category?: string): BlogPost[] {
  const q = query.toLowerCase().trim();
  return BLOG_POSTS.filter((post) => {
    const matchesCategory = !category || category === "all" || post.category.toLowerCase() === category.toLowerCase();
    const matchesQuery = !q || 
      post.title.toLowerCase().includes(q) || 
      post.description.toLowerCase().includes(q) ||
      post.tags.some(tag => tag.toLowerCase().includes(q));
    
    return matchesCategory && matchesQuery;
  });
}
